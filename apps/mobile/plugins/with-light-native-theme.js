/**
 * LANA — force the Android app theme to the LIGHT Material theme.
 *
 * Why: `app.json` declares `userInterfaceStyle: "light"` and every screen in
 * the app is light-only. But Expo prebuild still emits
 * `AppTheme parent="Theme.AppCompat.DayNight.NoActionBar"`, and there is no
 * night-mode lock. On a device whose OS is in dark mode, the native
 * `DatePickerDialog` used by `@react-native-community/datetimepicker`
 * (`display="default"`) then resolves `?android:attr/textColorPrimary` /
 * `textColorSecondary` to their DARK values (~white) while the dialog surface
 * stays light — so every unselected calendar day number renders as pale grey
 * on white and is effectively invisible. (The selected day, weekday headers,
 * month/year and nav arrows use explicit accent colours, so they stay
 * readable — matching the real-device report.)
 *
 * Fix: swap the theme parent to `Theme.AppCompat.Light.NoActionBar`. Now
 * `DayNight` can never resolve to dark, so the date/time pickers — and every
 * other native dialog (`Alert.alert`, …) — render with correct light-theme
 * contrast on every device and OEM, regardless of the OS dark-mode setting.
 * All existing `<item>`s on `AppTheme` are preserved untouched.
 *
 * This is the durable, version-controlled equivalent of editing
 * `android/app/src/main/res/values/styles.xml` (which is gitignored and
 * regenerated by `expo prebuild`). It touches no JS date logic — LH-26's
 * calendar-date serialization is unaffected.
 */
const { withAndroidStyles } = require('@expo/config-plugins');

const DAYNIGHT_PARENT = 'Theme.AppCompat.DayNight.NoActionBar';
const LIGHT_PARENT = 'Theme.AppCompat.Light.NoActionBar';

const withLightNativeTheme = (config) =>
  withAndroidStyles(config, (cfg) => {
    const styles = cfg.modResults?.resources?.style;
    if (Array.isArray(styles)) {
      for (const style of styles) {
        if (style?.$?.name === 'AppTheme' && style.$.parent === DAYNIGHT_PARENT) {
          style.$.parent = LIGHT_PARENT;
        }
      }
    }
    return cfg;
  });

module.exports = withLightNativeTheme;
